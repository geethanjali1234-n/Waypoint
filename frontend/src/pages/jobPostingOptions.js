export const STATE_OPTIONS = STATE_DATA.map(({ value, abbreviation }) => ({
  label: value,
  value,
  abbreviation,
}));

export const LOCATION_OPTIONS = STATE_DATA.flatMap(({ value: state, cities }) => (
  cities.map((city) => {
    const location = `${city}, ${state}`;
    return { label: location, value: location };
  })
));

const STATE_SEARCH_ALIASES = new Map([
  ['dc', 'district of columbia'],
  ...STATE_DATA.flatMap(({ value, abbreviation }) => [
    [abbreviation.toLowerCase(), value.toLowerCase()],
  ]),
]);

export function normalizeLocationSearch(location = '') {
  return String(location)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .map((token) => STATE_SEARCH_ALIASES.get(token) || token)
    .join(' ');
}

export function splitLocation(location = '') {
  const [cityPart, ...stateParts] = location.split(',');
  const rawState = stateParts.join(',').trim();
  const matchingState = STATE_OPTIONS.find(
    (state) => state.value.toLowerCase() === rawState.toLowerCase()
      || state.abbreviation.toLowerCase() === rawState.toLowerCase(),
  );

  return {
    city: cityPart?.trim() || '',
    state: matchingState?.value || rawState,
  };
}

export function normalizeLocation(location = '') {
  const { city, state } = splitLocation(location);
  const normalized = LOCATION_OPTIONS.find(
    (option) => option.value.toLowerCase() === `${city}, ${state}`.toLowerCase(),
  );

  return normalized?.value || location;
}
