import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { execSync } from 'child_process';
import { lanUrl, resolveLanAddress } from './lan-address.js';
import { configureAndroidSdk } from './android-sdk.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const androidDir = path.join(rootDir, 'android');
const versionPropsPath = path.join(androidDir, 'app', 'version.properties');
const versionJsonPath = path.join(rootDir, 'public', 'version.json');
const capConfigPath = path.join(rootDir, 'capacitor.config.json');
// For a hosted deployment, set WAYPOINT_API_URL (e.g. https://waypoint-backend.onrender.com/api)
// and WAYPOINT_WEB_URL (e.g. https://waypoint-frontend.onrender.com) so the APK works on any
// network. Otherwise the APK targets this machine's LAN address.
const hostedApiUrl = process.env.WAYPOINT_API_URL?.replace(/\/+$/, '');
const hostedWebUrl = process.env.WAYPOINT_WEB_URL?.replace(/\/+$/, '');
if (Boolean(hostedApiUrl) !== Boolean(hostedWebUrl)) {
  throw new Error('Set both WAYPOINT_API_URL and WAYPOINT_WEB_URL for a hosted APK build, or neither.');
}
const targetIp = hostedApiUrl ? null : resolveLanAddress(process.argv[2]);
const liveUrl = hostedWebUrl || lanUrl(5173, targetIp);
const mobileApiUrl = hostedApiUrl || `http://${targetIp}:8081/api`;

console.log('--- Waypoint In-Place APK Builder ---');

// 1. Auto-increment versionCode in version.properties
let currentCode = 2;
let versionName = '1.1.0';

if (fs.existsSync(versionPropsPath)) {
  const content = fs.readFileSync(versionPropsPath, 'utf-8');
  const codeMatch = content.match(/VERSION_CODE=(\d+)/);
  const nameMatch = content.match(/VERSION_NAME=([\d.]+)/);
  if (codeMatch) {
    currentCode = parseInt(codeMatch[1], 10) + 1;
  }
  if (nameMatch) {
    versionName = nameMatch[1];
  }
}

fs.writeFileSync(versionPropsPath, `VERSION_CODE=${currentCode}\nVERSION_NAME=${versionName}\n`);
console.log(`Incremented Android versionCode to: ${currentCode} (v${versionName})`);

// 2. Update public/version.json & src/constants/appVersion.js
if (fs.existsSync(versionJsonPath)) {
  const vJson = JSON.parse(fs.readFileSync(versionJsonPath, 'utf-8'));
  vJson.versionCode = currentCode;
  vJson.versionName = versionName;
  vJson.buildDate = new Date().toISOString().split('T')[0];
  vJson.downloadUrl = `${liveUrl}/downloads/waypoint.apk`;
  fs.writeFileSync(versionJsonPath, JSON.stringify(vJson, null, 2) + '\n');
  console.log(`Updated public/version.json with versionCode ${currentCode}`);
}

const appVersionJsPath = path.join(rootDir, 'src', 'constants', 'appVersion.js');
fs.writeFileSync(appVersionJsPath, `/**
 * Auto-generated by build-apk.js - DO NOT EDIT MANUALLY
 */
export const APP_CURRENT_VERSION = {
  versionName: '${versionName}',
  versionCode: ${currentCode},
  buildDate: '${new Date().toISOString().split('T')[0]}',
  appName: 'Waypoint',
};
`);
console.log(`Updated src/constants/appVersion.js with versionCode ${currentCode}`);

// 3. Ensure capacitor.config.json is in standalone mode for production APK
if (fs.existsSync(capConfigPath)) {
  const capConfig = JSON.parse(fs.readFileSync(capConfigPath, 'utf-8'));
  if (capConfig.server?.url) {
    delete capConfig.server.url;
    fs.writeFileSync(capConfigPath, JSON.stringify(capConfig, null, 2) + '\n');
    console.log('Set capacitor.config.json to standalone mode.');
  }
}

// 4. Build Vite frontend bundle
console.log('\nBuilding frontend assets with Vite...');
execSync('npm run build', {
  cwd: rootDir,
  stdio: 'inherit',
  env: {
    ...process.env,
    VITE_API_BASE_URL: mobileApiUrl,
    VITE_MOBILE_API_BASE_URL: mobileApiUrl,
    VITE_UPDATE_BASE_URL: liveUrl,
  },
});

// 5. Sync web assets with Capacitor Android
console.log('\nSyncing assets with Capacitor Android...');
execSync('npx cap sync android', { cwd: rootDir, stdio: 'inherit' });

// 6. Assemble Debug APK via Gradle
console.log('\nCompiling Android APK with Gradle...');
configureAndroidSdk(androidDir);
const gradlewCmd = process.platform === 'win32' ? '.\\gradlew.bat' : './gradlew';
execSync(`${gradlewCmd} assembleDebug`, { cwd: androidDir, stdio: 'inherit' });

// 7. Copy output APK to public/downloads/waypoint.apk and dist/downloads/waypoint.apk
const builtApkPath = path.join(androidDir, 'app', 'build', 'outputs', 'apk', 'debug', 'app-debug.apk');
const publicDownloadDir = path.join(rootDir, 'public', 'downloads');
const distDownloadDir = path.join(rootDir, 'dist', 'downloads');

fs.mkdirSync(publicDownloadDir, { recursive: true });
fs.mkdirSync(distDownloadDir, { recursive: true });

const targetPublicApk = path.join(publicDownloadDir, 'waypoint.apk');
const targetDistApk = path.join(distDownloadDir, 'waypoint.apk');

if (fs.existsSync(builtApkPath)) {
  fs.copyFileSync(builtApkPath, targetPublicApk);
  fs.copyFileSync(builtApkPath, targetDistApk);
  const sizeMb = (fs.statSync(targetPublicApk).size / (1024 * 1024)).toFixed(2);
  console.log(`\n🎉 SUCCESS: Built and deployed waypoint.apk (${sizeMb} MB)`);
  console.log(`Version: v${versionName} (versionCode: ${currentCode})`);
  console.log(`Download URL: ${liveUrl}/downloads/waypoint.apk`);
  console.log(`⚡ Existing installed apps will update directly in 1 tap without uninstalling!`);
} else {
  console.error(`ERROR: Built APK not found at ${builtApkPath}`);
  process.exit(1);
}
